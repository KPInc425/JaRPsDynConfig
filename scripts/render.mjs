#!/usr/bin/env node
/**
 * Render index.html for JaRP's DynConfig.
 *
 * The ARK servers read this page with -UseDynamicConfig and parse "Key=Value"
 * lines out of the body. Everything else on the page is cosmetic.
 *
 * Final value per setting = rates.base.json base x official.rates.json factor for
 * that same setting. Our baseline is already higher than official, so an official
 * 2x event doubles it again; an official interval factor of 0.6 shrinks our
 * interval to 60% of ours, which is the same thing as speeding it up.
 *
 * Why this exists: rates used to be hand-edited per event, and by the time a "2x"
 * page was live five of the nine values were still at 4x levels, because rolling a
 * number back meant remembering every place it had been changed. Now the base
 * lives in one file, the official factors are scraped from the rates channel, and
 * this script is the only thing that writes index.html.
 *
 * Usage:
 *   node scripts/render.mjs            # render index.html from the two JSON files
 *   node scripts/render.mjs --check    # exit 1 if index.html is stale (CI gate)
 *   node scripts/render.mjs --json     # print the computed values, write nothing
 *   node scripts/render.mjs --dry-run  # print the page that would be written
 */

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const baseFile = path.join(root, "rates.base.json");
const officialFile = path.join(root, "official.rates.json");
const outFile = path.join(root, "index.html");

const args = process.argv.slice(2);

function fmt(n) {
  // Trim float noise but never emit exponent notation, which the game cannot parse.
  const rounded = Math.round(n * 1e6) / 1e6;
  let s = rounded.toFixed(6).replace(/0+$/, "").replace(/\.$/, "");
  if (s === "-0") s = "0";
  return s;
}

const baseDoc = JSON.parse(await readFile(baseFile, "utf8"));
const official = JSON.parse(await readFile(officialFile, "utf8"));

const missing = Object.keys(baseDoc.values).filter(
  (k) => typeof official.multipliers?.[k] !== "number",
);
if (missing.length) {
  console.error(`official.rates.json is missing factors for: ${missing.join(", ")}`);
  process.exit(2);
}

const values = Object.entries(baseDoc.values).map(([key, spec]) => {
  const factor = official.multipliers[key];
  return { key, label: spec.label, base: spec.base, official: factor, value: fmt(spec.base * factor) };
});

function renderPage() {
  const lines = values.map((v) => `        ${v.key}=${v.value}`).join("\r\n");
  const provenance = ` ${official.title || "official rates"} (${official.posted_at || "unknown"}${official.source_message_id ? `, msg ${official.source_message_id}` : ""})`;
  return `<!DOCTYPE html>
<html lang="en">
    <head>
        <title>
            ${baseDoc.name}
        </title>
        <style>
            body {
                font-family: monospace;
                line-height: 1;
                word-wrap: break-word;
                white-space: pre-wrap;
            }
        </style>
        <!-- generated by scripts/render.mjs | our base x official:${provenance} -->
    <body>
${lines}
    </body>

</html>
`;
}

const page = renderPage();

if (args.includes("--json")) {
  console.log(JSON.stringify({ official, values }, null, 2));
  process.exit(0);
}

if (args.includes("--dry-run")) {
  process.stdout.write(page);
  process.exit(0);
}

if (args.includes("--check")) {
  const current = await readFile(outFile, "utf8").catch(() => "");
  const strip = (s) => s.replace(/<!--[^]*?-->/g, "").replace(/\s+/g, " ").trim();
  if (strip(current) === strip(page)) {
    console.log("index.html matches our base x current official rates.");
    process.exit(0);
  }
  console.error("index.html is stale. Run: node scripts/render.mjs");
  process.exit(1);
}

await writeFile(outFile, page, "utf8");
console.log(
  `Rendered: ${values.map((v) => `${v.key}=${v.value} (${v.base}x${v.official})`).join("  ")}`,
);
