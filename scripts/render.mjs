#!/usr/bin/env node
/**
 * Render index.html for JaRP's DynConfig.
 *
 * The ARK server reads this page with -UseDynamicConfig and parses "Key=Value"
 * lines out of the body. Everything else on the page is cosmetic.
 *
 * Why this exists: the rates used to be edited by hand per event, and by the time
 * a 2x page was live four of the nine values were still sitting at 4x levels,
 * because rolling a number back meant remembering every place it had been changed.
 * Now the base values live in rates.base.json, the current event multiplier lives
 * in multiplier.json, and this script is the only thing that writes index.html.
 *
 * Usage:
 *   node scripts/render.mjs                  # render from multiplier.json
 *   node scripts/render.mjs --multiplier 4   # render a one-off multiplier
 *   node scripts/render.mjs --check          # exit 1 if index.html is stale
 *   node scripts/render.mjs --json           # print the computed values only
 */

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const baseFile = path.join(root, "rates.base.json");
const multFile = path.join(root, "multiplier.json");
const outFile = path.join(root, "index.html");

const args = process.argv.slice(2);
const getArg = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};

function fmt(n) {
  // Trim float noise but never emit exponent notation, which the game cannot parse.
  const rounded = Math.round(n * 1e6) / 1e6;
  let s = rounded.toFixed(6).replace(/0+$/, "").replace(/\.$/, "");
  if (s === "-0") s = "0";
  return s;
}

function computeValues(baseDoc, multiplier) {
  const out = [];
  for (const [key, spec] of Object.entries(baseDoc.values)) {
    const raw = spec.mode === "divide" ? spec.base / multiplier : spec.base * multiplier;
    out.push({ key, value: fmt(raw), label: spec.label, mode: spec.mode });
  }
  return out;
}

function renderPage(baseDoc, multiplier, meta, values) {
  const lines = values.map((v) => `        ${v.key}=${v.value}`).join("\r\n");
  const banner = `<!-- generated by scripts/render.mjs | multiplier ${multiplier}x | ${meta.label || ""} -->`;
  return `<!DOCTYPE html>
<html lang="en">
    <head>
        <title>
            ${baseDoc.name}
        </title>
        <style>
            body {
                font-family: monospace;
                line-height: 1;
                word-wrap: break-word;
                white-space: pre-wrap;
            }
        </style>
${banner}
    <body>
${lines}
    </body>

</html>
`;
}

const baseDoc = JSON.parse(await readFile(baseFile, "utf8"));
const meta = JSON.parse(await readFile(multFile, "utf8"));
const multiplier = Number(getArg("--multiplier") ?? meta.value);

if (!Number.isFinite(multiplier) || multiplier <= 0) {
  console.error(`Invalid multiplier: ${getArg("--multiplier") ?? meta.value}`);
  process.exit(2);
}

const values = computeValues(baseDoc, multiplier);

if (args.includes("--json")) {
  console.log(JSON.stringify({ multiplier, values }, null, 2));
  process.exit(0);
}

const page = renderPage(baseDoc, multiplier, meta, values);

if (args.includes("--check")) {
  const current = await readFile(outFile, "utf8").catch(() => "");
  const strip = (s) => s.replace(/<!--[^]*?-->/g, "").replace(/\s+/g, " ").trim();
  if (strip(current) === strip(page)) {
    console.log(`index.html matches ${multiplier}x.`);
    process.exit(0);
  }
  console.error(`index.html does NOT match ${multiplier}x. Run: node scripts/render.mjs`);
  process.exit(1);
}

await writeFile(outFile, page, "utf8");
console.log(`Rendered index.html at ${multiplier}x: ${values.map((v) => `${v.key}=${v.value}`).join(" ")}`);
